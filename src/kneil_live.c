static atomic_t live_subscribed, raw_subscribed, info_subscribed;   /* CCC notify bits */
static atomic_t raw_on;                             /* CONTROL 0x10 / 0x11 (kept over a link loss) */
static atomic_t selftest_request;                   /* CONTROL 0x12 */
static atomic_t summary_request;                    /* INFO subscribed: send the summary */
static atomic_t connected;
