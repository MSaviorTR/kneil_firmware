static void dwt_cycle_counter_start(void)
{
	DCB->DEMCR |= DCB_DEMCR_TRCENA_Msk;   /* enable the DWT unit */
	DWT->CYCCNT = 0;
	DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
}

/* cycles -> microseconds x 10 (one decimal) */
static uint32_t cyc_to_us_x10(uint32_t cycles, uint32_t mhz)
{
	return (uint32_t)(((uint64_t)cycles * 10U) / mhz);
}

static void run_timing(void)
{
	uint64_t win_sum = 0, smp_sum = 0;
	uint32_t win_max = 0, win_min = UINT32_MAX, smp_max = 0, gait_max = 0;
	int n_win = 0, n_smp = 0, n_gait = 0;
	int per_class[KNEIL_N_CLASSES] = {0};

	dwt_cycle_counter_start();
	kneil_classifier_init(&clf);
	for (int s = 0; n_win < TIMING_WINDOWS; s++) {
		const float *a = kneil_tv_raw[(s / KNEIL_WIN_N) % KNEIL_TV_N][s % KNEIL_WIN_N];
		const uint32_t c0 = DWT->CYCCNT;
		const int cls = kneil_classifier_push(&clf, a[0], a[1], a[2]);
		const uint32_t dc = DWT->CYCCNT - c0;

		if (cls < 0) {           /* normal sample: low-pass and store only */
			smp_sum += dc;
			n_smp++;
			smp_max = MAX(smp_max, dc);
			continue;
		}
		win_sum += dc;           /* window classified: features + model (+ stride period) */
		n_win++;
		win_max = MAX(win_max, dc);
		win_min = MIN(win_min, dc);
		if (cls < KNEIL_N_CLASSES) {
			per_class[cls]++;
		}
		if (cls <= KNEIL_STAIRS_DOWN) {   /* walking and stairs also compute the stride period */
			n_gait++;
			gait_max = MAX(gait_max, dc);
		}
	}

	const uint32_t mhz = SystemCoreClock / 1000000U;
	const uint32_t win_mean = (uint32_t)(win_sum / (uint64_t)n_win);
	const uint32_t smp_mean = (uint32_t)(smp_sum / (uint64_t)n_smp);
	const uint32_t mean_us = cyc_to_us_x10(win_mean, mhz), max_us = cyc_to_us_x10(win_max, mhz);

	info("timing push() with class: %d windows; mean %u cycles (%u.%u us); max %u cycles (%u.%u us); "
	     "min %u cycles; CPU %u MHz", n_win, win_mean, mean_us / 10U, mean_us % 10U,
	     win_max, max_us / 10U, max_us % 10U, win_min, mhz);
	info("timing push() without class: %d samples; mean %u cycles; max %u cycles", n_smp, smp_mean, smp_max);
	info("timing walking/stairs windows %d (max %u cycles); windows per class 0-8: %d %d %d %d %d %d %d %d %d",
	     n_gait, gait_max, per_class[0], per_class[1], per_class[2], per_class[3], per_class[4],
	     per_class[5], per_class[6], per_class[7], per_class[8]);
	snprintk(timing_line, sizeof(timing_line), "timing per window: mean %u.%u us; max %u.%u us (CPU %u MHz)",
		 mean_us / 10U, mean_us % 10U, max_us / 10U, max_us % 10U, mhz);
}
#endif /* CONFIG_KNEIL_TINYML_SELFTEST */

