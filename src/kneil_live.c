static atomic_t raw_drops, live_drops, info_drops;

/* Bluetooth callbacks run on the small Bluetooth RX stack: they only set these bits, and the acq thread
 * writes the I lines (a formatted line there overflowed that stack). */
enum { BLE_EV_CONNECTED, BLE_EV_MTU, BLE_EV_DISCONNECTED };
static atomic_t ble_events;
static atomic_t disconnect_reason;

static void live_ccc_changed(const struct bt_gatt_attr *attr, uint16_t value)
{
	ARG_UNUSED(attr);
	atomic_set(&live_subscribed, value == BT_GATT_CCC_NOTIFY);
}

static void raw_ccc_changed(const struct bt_gatt_attr *attr, uint16_t value)
{
	ARG_UNUSED(attr);
	atomic_set(&raw_subscribed, value == BT_GATT_CCC_NOTIFY);
}

static void info_ccc_changed(const struct bt_gatt_attr *attr, uint16_t value)
{
	ARG_UNUSED(attr);
	atomic_set(&info_subscribed, value == BT_GATT_CCC_NOTIFY);
	if (value == BT_GATT_CCC_NOTIFY) {
		atomic_set(&summary_request, 1);    /* the acq thread sends it */
	}
}

/* CONTROL write (runs in the Bluetooth RX thread): only sets flags */
static ssize_t ctrl_write(struct bt_conn *conn, const struct bt_gatt_attr *attr, const void *buf,
			  uint16_t len, uint16_t offset, uint8_t flags)
{
	ARG_UNUSED(conn);
	ARG_UNUSED(attr);
	ARG_UNUSED(flags);
	if (offset != 0 || len != 1) {
		return BT_GATT_ERR(BT_ATT_ERR_INVALID_ATTRIBUTE_LEN);
	}
	switch (((const uint8_t *)buf)[0]) {
	case KNEIL_CTRL_RAW_START:
		atomic_set(&raw_on, 1);
		break;
	case KNEIL_CTRL_RAW_STOP:
		atomic_set(&raw_on, 0);
		break;
	case KNEIL_CTRL_SELFTEST:
		atomic_set(&selftest_request, 1);
		break;
	default:
		return BT_GATT_ERR(BT_ATT_ERR_VALUE_NOT_ALLOWED);
	}
	return len;
}

