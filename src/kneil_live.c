/* Why the board last restarted: a "software" reset during a test usually means a fault
 * (CONFIG_RESET_ON_FATAL_ERROR; the fault report is printed on RTT). */
static void read_reset_cause(void)
{
	uint32_t cause = 0;

	if (hwinfo_get_reset_cause(&cause) != 0) {
		return;
	}
	(void)hwinfo_clear_reset_cause();
	const char *what = (cause & RESET_SOFTWARE)   ? "software (a fault, or a reset command)" :
			   (cause & RESET_CPU_LOCKUP) ? "CPU lockup" :
			   (cause & RESET_WATCHDOG)   ? "watchdog" :
			   (cause & RESET_BROWNOUT)   ? "supply too low (brown-out)" :
			   (cause & RESET_PIN)        ? "reset pin" :
			   (cause & RESET_DEBUG)      ? "debugger" :
			   (cause & RESET_POR)        ? "power-on" : "other";

	snprintk(reset_line, sizeof(reset_line), "last reset: %s (cause 0x%08x)", what, cause);
}

