/*
 * KNEIL live: runs the kneil_tinyml activity classifier (model V3) on the es4l15ba1 board and sends
 * what it recognises over Bluetooth LE (KNEIL live protocol, section A, plus the INFO characteristic).
 * The PC receives it through the XIAO bridge. RTT carries a copy of the I and L lines for debugging.
 * Built instead of main.c when CONFIG_NEIL_APP_KNEIL_LIVE=y (kneil.conf).
 *
 * Threads (no dynamic memory, nothing is processed in interrupts):
 *  - acq (priority ACQ_PRIORITY): every 0.5 s reads the BMA580 FIFO (no INT wire: timer), converts the
 *    samples to the device frame, feeds the classifier (one window per second), builds LIVE and RAW packets.
 *  - ble (lower priority): sends the packets as notifications. The queues decouple it from sampling:
 *    RAW packets are dropped (and counted) if the link is too slow; LIVE packets are never dropped for RAW.
 *  - main: self-test and timing at boot, Bluetooth set-up, then it ends.
 */
