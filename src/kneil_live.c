static void run_selftest(void)
{
	/* k_cycle_get_32(): 1 MHz system timer (the 10 ms kernel tick is too coarse here) */
	const uint32_t c0 = k_cycle_get_32();
	const kneil_selftest_result_t r = kneil_selftest();
	const uint32_t dt_us = k_cyc_to_us_floor32(k_cycle_get_32() - c0);

	selftest_passed = (r.n_feature_fail == 0) && (r.n_class_mismatch == 0);
	/* printk has no float support in this build: max feature error in units of 1e-9 */
	const float err_e9 = r.max_feature_err * 1e9f;

	snprintk(selftest_line, sizeof(selftest_line),
		 "selftest %s vectors=%d feature_fail=%d class_mismatch=%d max_feature_err=%ue-9 time_us=%u",
		 selftest_passed ? "PASS" : "FAIL", r.n_vectors, r.n_feature_fail, r.n_class_mismatch,
		 (err_e9 < 4e9f) ? (unsigned int)err_e9 : 4000000000U, dt_us);
	info("%s", selftest_line);
}

