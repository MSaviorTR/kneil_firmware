static int16_t clamp16(int32_t v)
{
	return (int16_t)CLAMP(v, INT16_MIN, INT16_MAX);
}

static struct {
	int n;              /* windows seen since the last classifier reset (max 3) */
	int c[3];           /* c[0] newest raw class */
} hist;
static uint16_t live_seq, raw_seq;
static kneil_raw_t raw_pkt;
static int raw_target;      /* samples per RAW packet for the current MTU */

static void classifier_reset(void)
{
	kneil_classifier_init(&clf);
	hist.n = 0;
	raw_pkt.n = 0;              /* never glue non-contiguous samples */
}

static void queue_live(const kneil_live_t *p)
{
	struct live_item it;

	(void)kneil_live_encode(p, it.data, sizeof(it.data));
	if (k_msgq_put(&live_q, &it, K_NO_WAIT) != 0) {
		struct live_item old;   /* link stalled for 16 s: keep the newest LIVE packets */

		(void)k_msgq_get(&live_q, &old, K_NO_WAIT);
		(void)k_msgq_put(&live_q, &it, K_NO_WAIT);
		atomic_inc(&live_drops);
	}
	k_sem_give(&tx_sem);
}

static void queue_raw(void)
{
	struct raw_item it;
	const int len = kneil_raw_encode(&raw_pkt, it.data, sizeof(it.data));

	raw_pkt.n = 0;
	if (len <= 0) {
		return;
	}
	it.len = (uint16_t)len;
	if (k_msgq_put(&raw_q, &it, K_NO_WAIT) != 0) {
		atomic_inc(&raw_drops);   /* link too slow: drop RAW, never LIVE */
	} else {
		k_sem_give(&tx_sem);
	}
}

/* one classified window (once per second) */
static void on_window(int cls, uint32_t t_ms)
{
	kneil_live_t live = {0};

	hist.c[2] = hist.c[1];
	hist.c[1] = hist.c[0];
	hist.c[0] = cls;
	hist.n = MIN(hist.n + 1, 3);

	/* smoothed class = the library's majority-of-3 rule (kneil_metrics.c): the middle window changes
	 * only if both neighbours agree on another class. It is the class of the previous window (1 s delay). */
	int smooth = KNEIL_CLASS_NONE;

	if (hist.n == 2) {
		smooth = hist.c[1];             /* first window: no left neighbour, as it is */
	} else if (hist.n == 3) {
		smooth = (hist.c[2] == hist.c[0] && hist.c[2] != hist.c[1]) ? hist.c[2] : hist.c[1];
	}

	live.seq = live_seq++;
	live.t_ms = t_ms;
	live.cls = (uint8_t)cls;
	live.cls_smooth = (uint8_t)smooth;
	live.vote_pct = KNEIL_VOTE_NONE;
#if !defined(CONFIG_KNEIL_TINYML_MODEL_SMALL)
	float proba[KNEIL_N_CLASSES];

	if (kneil_model_predict_proba(clf.feat, KNEIL_N_FEATURES, proba, KNEIL_N_CLASSES) == 0) {
		live.vote_pct = (uint8_t)(proba[cls] * 100.0f + 0.5f);
	}
#endif
	live.flags = (selftest_passed ? KNEIL_FLAG_SELFTEST_OK : 0) |
		     (KNEIL_MODEL_LOWPASS_HZ > 0 ? KNEIL_FLAG_LOWPASS : 0) |
		     (IS_ENABLED(CONFIG_KNEIL_TINYML_MODEL_SMALL) ? KNEIL_FLAG_SMALL_MODEL : 0);
	/* mean of the 2 s window = mean features of the (low-passed) window the classifier used */
	live.mean_mg[0] = clamp16((int32_t)(clf.feat[KF_MEAN_X] * 1000.0f));
	live.mean_mg[1] = clamp16((int32_t)(clf.feat[KF_MEAN_Y] * 1000.0f));
	live.mean_mg[2] = clamp16((int32_t)(clf.feat[KF_MEAN_Z] * 1000.0f));
	live.battery_mv = 0;

	if (atomic_get(&connected) && atomic_get(&live_subscribed)) {
		queue_live(&live);
	}

	char line[96];   /* debugging: the same L line on RTT */

	if (kneil_live_to_line(&live, line, sizeof(line)) > 0) {
		printk("%s", line);
	}
}

static void on_sample(const int16_t s[3], uint32_t t_ms)
{
	int16_t mg[3];
	float g[3];

	for (int k = 0; k < 3; k++) {
		const int32_t d = axis_map[k].sign * (int32_t)s[axis_map[k].src];   /* device frame, LSB */

		mg[k] = clamp16((d * 1000 + (d >= 0 ? BMA580_LSB_PER_G / 2 : -BMA580_LSB_PER_G / 2)) /
				BMA580_LSB_PER_G);
		g[k] = (float)d * (1.0f / BMA580_LSB_PER_G);
	}

	/* RAW: 0.5 s per packet (25 samples), fewer samples if the ATT MTU is small */
	if (atomic_get(&raw_on) && atomic_get(&connected) && atomic_get(&raw_subscribed)) {
		if (raw_pkt.n == 0) {
			raw_target = MIN(KNEIL_RAW_N_NORMAL, KNEIL_RAW_N_FOR_MTU((int)atomic_get(&att_mtu)));
			raw_target = MAX(raw_target, 1);
			raw_pkt.seq = raw_seq++;
			raw_pkt.t_ms_first = t_ms;
		}
		memcpy(raw_pkt.xyz_mg[raw_pkt.n], mg, sizeof(mg));
		if (++raw_pkt.n >= raw_target) {
			queue_raw();
		}
	} else {
		raw_pkt.n = 0;
	}

	const int cls = kneil_classifier_push(&clf, g[0], g[1], g[2]);

	if (cls >= 0) {
		on_window(cls, t_ms);
	}
}

static void handle_requests(void)
{
	const atomic_val_t ev = atomic_clear(&ble_events);

	if (ev & BIT(BLE_EV_CONNECTED)) {
		info("ble connected");
	}
	if (ev & BIT(BLE_EV_MTU)) {
		info("ble att mtu=%ld", (long)atomic_get(&att_mtu));
	}
	if (ev & BIT(BLE_EV_DISCONNECTED)) {
		info("ble disconnected reason=0x%02lx", (long)atomic_get(&disconnect_reason));
	}
	if (atomic_cas(&summary_request, 1, 0)) {
		send_summary();
	}
	if (atomic_cas(&selftest_request, 1, 0)) {
		run_selftest();                    /* INFO line now, LIVE flags from the next window */
	}
}

static void acq_thread(void *a, void *b, void *c)
{
	static int16_t buf[BMA580_FIFO_MAX_FRAMES][3];
	uint32_t last_t = 0;
	atomic_val_t drops_shown = 0;
	int err;

	ARG_UNUSED(a);
	ARG_UNUSED(b);
	ARG_UNUSED(c);

	while ((err = bma580_fifo_start(i2c)) != 0) {
		sensor_state = "not answering (retrying every second)";
		info("bma580 start failed err=%d (retry in 1 s)", err);
		handle_requests();
		k_sleep(K_SECONDS(1));
	}
	sensor_state = "running";
	info("bma580 FIFO running: 50 Hz, +/-8 g, read every %d ms", FIFO_POLL_MS);
	classifier_reset();

	int64_t next = k_uptime_get();

	for (;;) {
		next += FIFO_POLL_MS;
		k_sleep(K_TIMEOUT_ABS_MS(next));
		handle_requests();

		bool overflow;
		const uint32_t t_read = k_uptime_get_32();
		const int n = bma580_fifo_read(i2c, buf, ARRAY_SIZE(buf), &overflow);

		if (n < 0) {
			info("bma580 FIFO read error %d: restart", n);
			sensor_state = (bma580_fifo_start(i2c) == 0) ? "running (restarted after a read error)"
								     : "read error, restart failed";
			classifier_reset();
			continue;
		}
		if (overflow) {
			info("bma580 FIFO overflow: samples lost, classifier restarted");
			classifier_reset();
		}
		for (int i = 0; i < n; i++) {
			/* time of each sample: the newest one was read just now, the others 20 ms apart */
			uint32_t t = t_read - (uint32_t)(n - 1 - i) * SAMPLE_MS;

			if ((int32_t)(t - last_t) <= 0) {
				t = last_t + 1;
			}
			last_t = t;
			on_sample(buf[i], t);
		}

		const atomic_val_t d = atomic_get(&raw_drops) + atomic_get(&live_drops) + atomic_get(&info_drops);

		if (d != drops_shown) {
			info("ble drops raw %ld live %ld info %ld", (long)atomic_get(&raw_drops),
			     (long)atomic_get(&live_drops), (long)atomic_get(&info_drops));
			drops_shown = d;
		}
	}
}

K_THREAD_STACK_DEFINE(acq_stack, 3072);
K_THREAD_STACK_DEFINE(ble_stack, 1536);
static struct k_thread acq_tdata, ble_tdata;

/* ------------------------------------------------------------------------------------------------ */
int main(void)
{
	read_reset_cause();
	info("KNEIL live firmware %s (%s)", KNEIL_FW_VERSION, CONFIG_BOARD);
	info("%s", reset_line);
	info("model %s: forest %d trees %d nodes, tree %d nodes; %d features; %d Hz; low-pass %d Hz",
	     IS_ENABLED(CONFIG_KNEIL_TINYML_MODEL_SMALL) ? "tree" : "forest", KNEIL_FOREST_TREES,
	     KNEIL_FOREST_NODES, KNEIL_TREE_NODES, KNEIL_MODEL_N_FEATURES, KNEIL_MODEL_FS_HZ,
	     KNEIL_MODEL_LOWPASS_HZ);
	info("ram classifier=%u bytes metrics=%u bytes", (unsigned int)sizeof(kneil_classifier_t),
	     (unsigned int)sizeof(kneil_metrics_t));

	run_selftest();
#if defined(CONFIG_KNEIL_TINYML_SELFTEST)
	run_timing();
#endif

	if (!device_is_ready(i2c)) {
		info("i2c not ready");
		return 0;
	}

	int err = bt_enable(NULL);

	if (err) {
		info("ble enable failed err=%d", err);
	} else {
		bt_addr_le_t addr[CONFIG_BT_ID_MAX];
		size_t count = ARRAY_SIZE(addr);

		bt_id_get(addr, &count);
		snprintk(adv_name, sizeof(adv_name), "%s%02X%02X", KNEIL_NAME_PREFIX,
			 addr[0].a.val[1], addr[0].a.val[0]);
		(void)bt_set_name(adv_name);
		bt_gatt_cb_register(&gatt_callbacks);
		k_work_submit(&adv_work);
		info("ble advertising as %s", adv_name);
	}

	k_thread_create(&ble_tdata, ble_stack, K_THREAD_STACK_SIZEOF(ble_stack), ble_thread,
			NULL, NULL, NULL, BLE_PRIORITY, 0, K_NO_WAIT);
	k_thread_create(&acq_tdata, acq_stack, K_THREAD_STACK_SIZEOF(acq_stack), acq_thread,
			NULL, NULL, NULL, ACQ_PRIORITY, K_FP_REGS, K_NO_WAIT);
	k_thread_name_set(&ble_tdata, "kneil_ble");
	k_thread_name_set(&acq_tdata, "kneil_acq");
	return 0;
}
